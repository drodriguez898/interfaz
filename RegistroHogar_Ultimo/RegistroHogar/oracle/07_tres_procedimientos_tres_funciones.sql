CREATE PROCEDURE RH_REGISTRAR_VISITA_PROC (p_id IN NUMBER, p_num IN NUMBER, p_hogar IN NUMBER, p_enc IN NUMBER) AUTHID CURRENT_USER AS
BEGIN
  INSERT INTO VISITA (IDVISITA, NUMEROVISITA, FECHA, IDHOGAR, IDENCUESTADOR) VALUES (p_id, p_num, SYSDATE, p_hogar, p_enc);
END;
/
SHOW ERRORS PROCEDURE RH_REGISTRAR_VISITA_PROC
CREATE PROCEDURE RH_TRANSMITIR_ENC_PROC (p_encuesta IN NUMBER) AUTHID CURRENT_USER AS
BEGIN
  UPDATE ENCUESTA SET ESTADO='TRANSMITIDO', FECHATRANSMISION=SYSDATE WHERE IDENCUESTA=p_encuesta AND UPPER(NVL(ESTADO,'EN_PROGRESO')) NOT IN ('CERRADO','TRANSMITIDO');
  IF SQL%ROWCOUNT <> 1 THEN RAISE_APPLICATION_ERROR(-20102, 'El estado de la encuesta cambio; actualice la pantalla.'); END IF;
END;
/
SHOW ERRORS PROCEDURE RH_TRANSMITIR_ENC_PROC
CREATE PROCEDURE RH_CERRAR_ENC_PROC (p_admin IN NUMBER, p_encuesta IN NUMBER) AUTHID CURRENT_USER AS
BEGIN
  UPDATE ENCUESTA SET ESTADO='CERRADO', FECHACIERRE=SYSDATE, IDADMINISTRADOR=p_admin WHERE IDENCUESTA=p_encuesta;
  IF SQL%ROWCOUNT <> 1 THEN RAISE_APPLICATION_ERROR(-20103, 'No se pudo cerrar la encuesta.'); END IF;
END;
/
SHOW ERRORS PROCEDURE RH_CERRAR_ENC_PROC
CREATE FUNCTION RH_SIG_NUM_VISITA_FN (p_hogar IN NUMBER) RETURN NUMBER AUTHID CURRENT_USER AS v_num NUMBER;
BEGIN
  SELECT NVL(MAX(NUMEROVISITA),0)+1 INTO v_num FROM VISITA WHERE IDHOGAR=p_hogar;
  RETURN v_num;
END;
/
SHOW ERRORS FUNCTION RH_SIG_NUM_VISITA_FN
CREATE FUNCTION RH_GASTOS_CERRADOS_FN (p_encuesta IN NUMBER) RETURN NUMBER AUTHID CURRENT_USER AS v_total NUMBER;
BEGIN
  SELECT COUNT(g.IDGASTO) INTO v_total FROM DIACICLO d LEFT JOIN GASTO g ON g.IDDIA=d.IDDIA WHERE d.IDENCUESTA=p_encuesta AND d.NUMERODIA BETWEEN 1 AND 14 AND UPPER(TRIM(d.ESTADO))='CERRADO';
  RETURN v_total;
END;
/
SHOW ERRORS FUNCTION RH_GASTOS_CERRADOS_FN
CREATE FUNCTION RH_OBSERVACIONES_PEND_FN (p_encuesta IN NUMBER) RETURN NUMBER AUTHID CURRENT_USER AS v_total NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_total FROM OBSERVACION o JOIN GASTO g ON g.IDGASTO=o.IDGASTO JOIN DIACICLO d ON d.IDDIA=g.IDDIA WHERE d.IDENCUESTA=p_encuesta AND UPPER(TRIM(o.ESTADO))='PENDIENTE';
  RETURN v_total;
END;
/
