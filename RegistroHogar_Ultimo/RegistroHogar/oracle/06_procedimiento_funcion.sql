CREATE PROCEDURE RH_CERRAR_DIA_PROC (p_iddia IN NUMBER) AUTHID CURRENT_USER AS
BEGIN
    UPDATE DIACICLO SET ESTADO = 'CERRADO' WHERE IDDIA = p_iddia;
    IF SQL%ROWCOUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20101, 'No se pudo cerrar el día.');
    END IF;
END;
/
SHOW ERRORS PROCEDURE RH_CERRAR_DIA_PROC

CREATE FUNCTION RH_DIAS_CERRADOS_FN (p_idencuesta IN NUMBER) RETURN NUMBER AUTHID CURRENT_USER AS
    v_total NUMBER;
BEGIN
    SELECT COUNT(DISTINCT NUMERODIA) INTO v_total FROM DIACICLO
    WHERE IDENCUESTA = p_idencuesta AND NUMERODIA BETWEEN 1 AND 14
      AND UPPER(TRIM(ESTADO)) = 'CERRADO';
    RETURN v_total;
END;
/
SHOW ERRORS FUNCTION RH_DIAS_CERRADOS_FN

GRANT EXECUTE ON RH_CERRAR_DIA_PROC TO RH_JEFE_HOGAR;
GRANT EXECUTE ON RH_DIAS_CERRADOS_FN TO RH_ADMINISTRADOR;
