WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE OR REPLACE VIEW RH_JEFE_ACTIVO AS
SELECT IDENCUESTADO, IDHOGAR FROM ENCUESTADO
WHERE IDHOGAR IS NOT NULL AND DOCUMENTO IS NOT NULL AND CONTRASENA IS NOT NULL
  AND UPPER(TRIM(CAST(ESENCARGADOGASTOS AS VARCHAR2(10)))) IN ('S','SI','SÍ','1');
GRANT SELECT ON RH_JEFE_ACTIVO TO RH_JEFE_HOGAR;
GRANT SELECT, INSERT, UPDATE, DELETE ON ENCUESTADOR TO RH_ADMINISTRADOR;
PROMPT Permisos de eliminacion actualizados.
WHENEVER SQLERROR CONTINUE NONE
