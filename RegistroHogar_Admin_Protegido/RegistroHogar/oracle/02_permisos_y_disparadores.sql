-- 1. Gastos: impide reubicar gastos y proteger días y encuestas cerrados.
CREATE OR REPLACE TRIGGER RH_GASTO_EDITABLE
BEFORE INSERT OR UPDATE OR DELETE ON GASTO
FOR EACH ROW
DECLARE
  v_dia DIACICLO.IDDIA%TYPE;
  v_encuesta ENCUESTA.IDENCUESTA%TYPE;
  v_estado_encuesta ENCUESTA.ESTADO%TYPE;
  v_estado_dia DIACICLO.ESTADO%TYPE;
  v_cuenta VARCHAR2(128) := SYS_CONTEXT('USERENV','SESSION_USER');
BEGIN
  IF UPDATING AND (:NEW.IDDIA IS NULL OR :OLD.IDDIA IS NULL OR :NEW.IDDIA <> :OLD.IDDIA
                   OR :NEW.IDGASTO IS NULL OR :NEW.IDGASTO <> :OLD.IDGASTO) THEN
    RAISE_APPLICATION_ERROR(-20011, 'El gasto no puede cambiar de identificador ni de dia.');
  END IF;
  IF DELETING THEN v_dia := :OLD.IDDIA; ELSE v_dia := :NEW.IDDIA; END IF;

  SELECT IDENCUESTA INTO v_encuesta FROM DIACICLO WHERE IDDIA = v_dia;
  SELECT UPPER(TRIM(ESTADO)) INTO v_estado_encuesta
    FROM ENCUESTA WHERE IDENCUESTA = v_encuesta FOR UPDATE;
  SELECT UPPER(TRIM(ESTADO)) INTO v_estado_dia
    FROM DIACICLO WHERE IDDIA = v_dia AND IDENCUESTA = v_encuesta FOR UPDATE;

  IF NOT (DELETING AND v_cuenta = 'RH_APP_ADMIN')
     AND (v_estado_encuesta = 'CERRADO'
          OR ((v_estado_encuesta = 'TRANSMITIDO' OR v_estado_dia = 'CERRADO')
              AND (NOT UPDATING OR v_cuenta <> 'RH_APP_ADMIN'))) THEN
    RAISE_APPLICATION_ERROR(-20012, 'El gasto pertenece a un dia o encuesta de solo lectura.');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20013, 'El gasto debe pertenecer a un dia y una encuesta existentes.');
END;
/

-- 2. Días: posición válida del ciclo y cierre irreversible.
CREATE OR REPLACE TRIGGER RH_DIA_CIERRE
BEFORE INSERT OR UPDATE ON DIACICLO
FOR EACH ROW
DECLARE
  v_estado ENCUESTA.ESTADO%TYPE;
BEGIN
  IF :NEW.NUMERODIA IS NULL OR :NEW.NUMERODIA <> TRUNC(:NEW.NUMERODIA)
     OR :NEW.NUMERODIA NOT BETWEEN 1 AND 14 THEN
    RAISE_APPLICATION_ERROR(-20021, 'El numero de dia debe estar entre 1 y 14.');
  END IF;

  IF UPDATING AND (:NEW.IDDIA IS NULL OR :NEW.IDDIA <> :OLD.IDDIA
       OR :NEW.IDENCUESTA IS NULL OR :OLD.IDENCUESTA IS NULL OR :NEW.IDENCUESTA <> :OLD.IDENCUESTA
       OR :OLD.NUMERODIA IS NULL OR :NEW.NUMERODIA <> :OLD.NUMERODIA
       OR UPPER(TRIM(:OLD.ESTADO)) = 'CERRADO') THEN
    RAISE_APPLICATION_ERROR(-20022, 'El dia no se puede reubicar ni modificar despues del cierre.');
  END IF;

  SELECT UPPER(TRIM(ESTADO)) INTO v_estado
  FROM ENCUESTA WHERE IDENCUESTA = :NEW.IDENCUESTA FOR UPDATE;
  IF v_estado IN ('TRANSMITIDO','CERRADO') THEN
    RAISE_APPLICATION_ERROR(-20023, 'La encuesta ya fue transmitida o cerrada.');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20024, 'El dia debe pertenecer a una encuesta existente.');
END;
/

-- 3. Encuesta: transmite y cierra solo con el ciclo completo y sin pendientes.
CREATE OR REPLACE TRIGGER RH_ENCUESTA_FLUJO
BEFORE INSERT OR UPDATE ON ENCUESTA
FOR EACH ROW
DECLARE
  anterior VARCHAR2(30) := NVL(UPPER(TRIM(:OLD.ESTADO)), 'EN_PROGRESO');
  siguiente VARCHAR2(30) := NVL(UPPER(TRIM(:NEW.ESTADO)), 'EN_PROGRESO');
  cuenta VARCHAR2(128) := SYS_CONTEXT('USERENV','SESSION_USER');
  dias NUMBER;
  gastos NUMBER;
  pendientes NUMBER;
BEGIN
  IF INSERTING AND siguiente <> 'EN_PROGRESO' THEN
    RAISE_APPLICATION_ERROR(-20031, 'Una encuesta nueva debe estar en progreso.');
  END IF;
  IF UPDATING AND (anterior = 'CERRADO'
       OR :NEW.IDENCUESTA IS NULL OR :NEW.IDENCUESTA <> :OLD.IDENCUESTA
       OR :NEW.IDHOGAR IS NULL OR :OLD.IDHOGAR IS NULL OR :NEW.IDHOGAR <> :OLD.IDHOGAR) THEN
    RAISE_APPLICATION_ERROR(-20032, 'Una encuesta cerrada o su asignacion de hogar es de solo lectura.');
  END IF;
  IF UPDATING AND cuenta = 'RH_APP_ENC'
     AND (siguiente = anterior OR UPDATING('IDADMINISTRADOR') OR UPDATING('IDSUPERVISOR')
          OR UPDATING('FECHACIERRE')) THEN
    RAISE_APPLICATION_ERROR(-20033, 'El encuestador solo puede transmitir la encuesta.');
  END IF;
  IF UPDATING AND siguiente <> anterior THEN
    IF (siguiente = 'CERRADO' AND (anterior <> 'TRANSMITIDO' OR cuenta = 'RH_APP_ENC'
                                  OR :NEW.IDADMINISTRADOR IS NULL))
       OR (siguiente = 'TRANSMITIDO' AND (anterior NOT IN ('EN_PROGRESO','EN_CORRECCION')
                                          OR cuenta = 'RH_APP_ADMIN'))
       OR (cuenta = 'RH_APP_ENC' AND siguiente <> 'TRANSMITIDO') THEN
      RAISE_APPLICATION_ERROR(-20033, 'El cambio de estado no corresponde a este rol o etapa.');
    END IF;

    IF siguiente IN ('TRANSMITIDO','CERRADO') THEN
      SELECT COUNT(DISTINCT d.NUMERODIA), COUNT(g.IDGASTO)
        INTO dias, gastos
        FROM DIACICLO d LEFT JOIN GASTO g ON g.IDDIA = d.IDDIA
        WHERE d.IDENCUESTA = :NEW.IDENCUESTA AND d.NUMERODIA BETWEEN 1 AND 14
          AND d.NUMERODIA = TRUNC(d.NUMERODIA) AND UPPER(TRIM(d.ESTADO)) = 'CERRADO';

      SELECT COUNT(*) INTO pendientes
        FROM OBSERVACION o JOIN GASTO g ON g.IDGASTO = o.IDGASTO
        JOIN DIACICLO d ON d.IDDIA = g.IDDIA
        WHERE d.IDENCUESTA = :NEW.IDENCUESTA AND UPPER(TRIM(o.ESTADO)) = 'PENDIENTE';

      IF dias <> 14 OR gastos = 0 OR pendientes > 0 THEN
        RAISE_APPLICATION_ERROR(-20034, 'Se requieren 14 dias cerrados, gastos y ninguna observacion pendiente.');
      END IF;
      IF siguiente = 'TRANSMITIDO' AND :NEW.FECHATRANSMISION IS NULL THEN
        :NEW.FECHATRANSMISION := SYSDATE;
      ELSIF siguiente = 'CERRADO' AND :NEW.FECHACIERRE IS NULL THEN
        :NEW.FECHACIERRE := SYSDATE;
      END IF;
    END IF;
  END IF;
END;
/

-- 4. Visita: solo un encuestador activo y asignado puede registrar la visita.
CREATE OR REPLACE TRIGGER RH_VISITA_ASIGNADA
BEFORE INSERT ON VISITA
FOR EACH ROW
DECLARE
  asignado HOGAR.IDENCUESTADOR%TYPE;
  estado ENCUESTADOR.ESTADO%TYPE;
BEGIN
  SELECT IDENCUESTADOR INTO asignado FROM HOGAR WHERE IDHOGAR = :NEW.IDHOGAR FOR UPDATE;
  IF asignado IS NULL OR :NEW.IDENCUESTADOR IS NULL OR asignado <> :NEW.IDENCUESTADOR THEN
    RAISE_APPLICATION_ERROR(-20041, 'El encuestador no esta asignado a este hogar.');
  END IF;
  SELECT UPPER(TRIM(ESTADO)) INTO estado FROM ENCUESTADOR WHERE IDENCUESTADOR = asignado;
  IF NVL(estado, '-') <> 'ACTIVO' THEN
    RAISE_APPLICATION_ERROR(-20042, 'El encuestador debe estar activo para registrar visitas.');
  END IF;
  IF :NEW.FECHA IS NULL THEN :NEW.FECHA := SYSDATE; END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20043, 'El hogar y el encuestador deben existir.');
END;
/

