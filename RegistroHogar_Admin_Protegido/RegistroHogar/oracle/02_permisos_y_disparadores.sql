BEGIN
  SELECT COUNT(*) INTO validos FROM USER_OBJECTS
  WHERE OBJECT_TYPE = 'TRIGGER' AND STATUS = 'VALID'
    AND OBJECT_NAME IN ('RH_GASTO_EDITABLE','RH_DIA_CIERRE','RH_ENCUESTA_FLUJO','RH_VISITA_ASIGNADA');
  IF validos <> 4 THEN
    RAISE_APPLICATION_ERROR(-20001, 'Hay disparadores invalidos. Consulta USER_ERRORS.');
  END IF;
END;
