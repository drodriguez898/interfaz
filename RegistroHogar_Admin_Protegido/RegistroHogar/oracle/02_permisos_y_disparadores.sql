CREATE OR REPLACE VIEW RH_ACCESO AS
SELECT IDCOORDINADOR AS ID, NOMBRE, DOCUMENTO, CONTRASENA, 0 AS HOGAR,
       'ADMINISTRADOR' AS ROL
FROM COORDINADOR WHERE ROL_ACCESO = 'ADMINISTRADOR'
UNION ALL
SELECT IDENCUESTADOR, NOMBRE, DOCUMENTO, CONTRASENA, 0, 'ENCUESTADOR'
FROM ENCUESTADOR WHERE UPPER(TRIM(ESTADO)) = 'ACTIVO'
UNION ALL
SELECT IDENCUESTADO, NOMBRE, DOCUMENTO, CONTRASENA, IDHOGAR, 'JEFE_HOGAR'
FROM ENCUESTADO
WHERE IDHOGAR IS NOT NULL
  AND UPPER(TRIM(CAST(ESENCARGADOGASTOS AS VARCHAR2(10)))) IN ('S','SI','SÍ','1');

CREATE OR REPLACE VIEW RH_PERSONAS_HOGAR AS
SELECT IDENCUESTADO, IDHOGAR, NOMBRE FROM ENCUESTADO;

CREATE OR REPLACE VIEW RH_JEFE_ACTIVO AS
SELECT IDENCUESTADO, IDHOGAR FROM ENCUESTADO
WHERE IDHOGAR IS NOT NULL AND DOCUMENTO IS NOT NULL AND CONTRASENA IS NOT NULL
  AND UPPER(TRIM(CAST(ESENCARGADOGASTOS AS VARCHAR2(10)))) IN ('S','SI','SÍ','1');

CREATE OR REPLACE VIEW RH_ESTADO_ENCUESTADOR AS
SELECT IDENCUESTADOR, ESTADO FROM ENCUESTADOR;

